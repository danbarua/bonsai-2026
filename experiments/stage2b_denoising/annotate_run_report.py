"""Write a preserved annotation beside a stage-3 run report.

## Why this is a committed script and not a heredoc

The annotation is a durable object in the science bucket. Generating it
from an ephemeral shell block would make its generator a chat transcript
-- CLAUDE.md principle 24's load-bearing-scratch shape, and the remedy
principle 24 names is promotion to committed code rather than citation of
the capture. So: committed, runnable, and re-runnable.

## Why an annotation rather than an edit

The report records what the run reported. It is not edited. A correction
that overwrites the original claim destroys the evidence that the claim
was made -- and "the record said X and was later found wrong" is a
different, more useful fact than "the record says Y".

So the annotation is a SEPARATE object whose name sorts adjacent to the
report it annotates, and the report is left exactly as the run wrote it.

## The incident this exists for

`run_ladder_stage3.py` reported `STAGE3_OK` for the amended-grid re-run on
2026-08-08 while two conditions (T, lattice) selected the grid floor
1e-06 -- which DESIGN.md's amended frozen procedure names as a HALT
condition. The halt was frozen into the document and never written into
the driver, so the verdict recorded that no such gate existed, not that
one was evaluated and cleared.

Anyone reading the report alone would take `STAGE3_OK` at face value.
This makes the artifact self-correcting.
"""
import argparse
import json
import os
import sys

_THIS_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _THIS_DIR)

import stage2b_gcs as gcs                                    # noqa: E402

LADDER_STAGE = 3
SPLIT = "train"


def annotation_object_name(run_id, sequence=None):
    """Sorts immediately after the report it annotates, so a listing shows
    them together. `stage3_report` prefix keeps it RUN_SCOPED, matching the
    class of the report itself.

    `sequence` appends rather than replaces. Annotations are append-only: a
    later correction does not overwrite an earlier one, because destroying
    the first correction to make room for a better one is the same failure
    as editing the report. `read_run_report` surfaces all of them."""
    suffix = "_annotation" if sequence is None else f"_annotation_{sequence}"
    return gcs.object_path(stage=LADDER_STAGE, condition=None,
                           kind=f"stage3_report_{run_id}{suffix}",
                           ext="json", split=SPLIT)


def build_annotation(run_id):
    report = gcs.object_path(stage=LADDER_STAGE, condition=None,
                             kind=f"stage3_report_{run_id}", ext="json",
                             split=SPLIT)
    return {
        "annotates": report,
        # THE machine-decidable field. The reviewer standard (c2gpt archive
        # 2026-08-08T08:56:03Z) requires "an unambiguous machine-readable
        # supersession/correction field such that automated consumers cannot
        # continue treating the old STAGE3_OK verdict as current without
        # explicitly ignoring the correction... make current validity
        # machine-decidable."
        #
        # read_run_report()'s refusal satisfies the first half -- a consumer
        # cannot reach the verdict without handling the exception or naming
        # the opt-out. This block satisfies the second: a consumer that DOES
        # handle it can decide validity from booleans and enums rather than
        # by parsing prose written by hand under time pressure.
        "supersession": {
            "verdict_superseded": True,
            "verdict_as_recorded": "STAGE3_OK",
            "current_validity": "invalid_as_gate_evidence",
            "reason_code": "gate_not_implemented",
            "gate": "alpha == 1e-6 grid-floor halt (DESIGN.md amended "
                    "frozen procedure)",
            "numerical_artifacts_admissible": True,
            "admissibility_note":
                "The defect was in the readiness verdict and its "
                "enforcement, not in the reported ridge computation. The "
                "run's numerical artifacts remain admissible evidence.",
            "superseded_at_utc": "2026-08-08T08:20:00Z",
        },
        "written_by": "stage2b-lead, after the run, at the orchestrator's "
                      "instruction; generated by this committed script",
        "why_a_separate_object":
            "The report records what the run reported and is not edited. "
            "Overwriting the original claim would destroy the evidence that "
            "the claim was made, and 'the record said X and was later found "
            "wrong' is a more useful fact than 'the record says Y'.",
        "correction": {
            "verdict_as_recorded": "STAGE3_OK",
            "what_that_verdict_MEANT":
                "STAGE3_OK AS THEN DEFINED. The driver's halt set did not "
                "include the grid-floor condition, so the verdict records "
                "that no such gate was implemented -- NOT that one was "
                "evaluated and cleared.",
            "the_unimplemented_gate":
                "DESIGN.md's amended frozen procedure, verbatim: 'HALT for "
                "review if any production condition selects 1e-6.' Frozen in "
                "the document hours before the grid extension was "
                "implemented; never written into run_ladder_stage3.py.",
            "the_condition_DID_occur":
                "T and lattice both selected alpha=1e-06, the grid floor, "
                "genuinely -- argmin at index 0, no tie within "
                "ALPHA_TIE_TOL=1e-10. rewired and curr_random resolved to "
                "interior 1e-05; raw_505 and raw_784 are flat to 1e-10 "
                "across four decades and tie-break upward to 1e-03; "
                "pre_evolution is interior at 1e+03.",
            "status":
                "Anomaly stands, escalated for review before Stage 4. NOT "
                "resolved by this annotation, and explicitly NOT a trigger "
                "for further grid extension -- the frozen procedure names a "
                "floor pin as an anomaly and forbids extension as its "
                "remedy.",
            "fix":
                "floor_halt_reason() implemented in run_ladder_stage3.py at "
                "commit 4173bf7, break-tested in both directions and "
                "confirmed to FAIL against the exact driver that produced "
                "this report (commit 817ac08, which imports cleanly with "
                "step7_ridge intact -- so the failure is the missing gate, "
                "not a broken module).",
        },
        "artifacts_this_run_produced": {
            "ridge_cv": gcs.object_path(stage=LADDER_STAGE, condition=None,
                                        kind="ridge_cv_g13_88edf9ac",
                                        ext="json", split=SPLIT),
            "ridge_final": gcs.object_path(stage=LADDER_STAGE, condition=None,
                                           kind="ridge_final_g13_88edf9ac",
                                           ext="npz", split=SPLIT),
            "note": "create-once and untouched by this annotation. Phase B's "
                    "nine-decade tables remain beside them as history.",
        },
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--run-id", required=True,
                        help="the report's run id, e.g. 20260808T014606Z")
    parser.add_argument("--bucket", default=None)
    parser.add_argument("--credentials", default=None)
    parser.add_argument("--sequence", default=None,
                        help="append as annotation_<N> instead of replacing; "
                             "annotations are append-only")
    parser.add_argument("--dry-run", action="store_true",
                        help="print the annotation and write nothing")
    args = parser.parse_args(argv)

    name = annotation_object_name(args.run_id, args.sequence)
    payload = build_annotation(args.run_id)
    print(json.dumps(payload, indent=2, sort_keys=True))
    print(f"\nobject: {name}\nclass : {gcs.artifact_class(name)}")

    if args.dry_run:
        print("\n--dry-run: nothing written")
        return 0

    bucket = gcs.get_bucket(name=args.bucket, credentials=args.credentials)
    if gcs.object_exists(name, bucket=bucket):
        print("\nannotation already exists; refusing to replace it "
              "(a correction that overwrites a correction is not a record)")
        return 1

    import tempfile
    with tempfile.TemporaryDirectory() as tmp:
        local = os.path.join(tmp, "annotation.json")
        with open(local, "w", encoding="utf-8") as handle:
            handle.write(json.dumps(payload, indent=2, sort_keys=True))
        gcs.upload_file(local, name, bucket=bucket)
    print(f"\nwritten: {name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
